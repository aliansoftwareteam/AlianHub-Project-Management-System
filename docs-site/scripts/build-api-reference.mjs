// Splits docs/API.md (written by `npm run api:doc` at the repo root) into one page per section,
// so the API reference here never drifts from the generated source.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(site, '..')
const source = readFileSync(join(repoRoot, 'docs/API.md'), 'utf8').replace(/\r\n/g, '\n')
const outDir = join(site, 'api')

const BASICS = new Set([
  'Base URL and versions', 'Authentication', 'Responses and errors', 'Rate limiting',
  'Ids and dates', 'Pagination', 'Webhook deliveries', 'Stability',
])
const APPENDIX = 'Appendix: every other route'

const githubSlug = (s) => s.trim().toLowerCase().replace(/`/g, '').replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-')

// Mirrors @mdit-vue/shared slugify, which VitePress uses for heading ids.
const vitepressSlug = (s) => s
  .normalize('NFKD')
  .replace(/[\u0300-\u036F]/g, '')
  .replace(/[\s~`!@#$%^&*()\-_+=[\]{}|\\;:"'“”‘’<>,.?/]+/g, '-')
  .replace(/-{2,}/g, '-')
  .replace(/^-+|-+$/g, '')
  .replace(/^(\d)/, '_$1')
  .toLowerCase()

const pageSlug = (title) => (title === APPENDIX ? 'all-routes' : vitepressSlug(title))

const lines = source.split('\n')
const intro = []
const sections = []
let current = null
let inFence = false
for (const line of lines) {
  if (line.startsWith('```')) inFence = !inFence
  const h2 = !inFence && /^## (.+)$/.exec(line)
  if (h2) {
    current = { title: h2[1].trim(), body: [] }
    sections.push(current)
    continue
  }
  if (current) current.body.push(line)
  else if (!/^# /.test(line)) intro.push(line)
}
const pages = sections.filter((s) => s.title !== 'Contents')

const anchors = new Map()
for (const page of pages) {
  const slug = pageSlug(page.title)
  anchors.set(githubSlug(page.title), `/api/${slug}`)
  let fence = false
  for (const line of page.body) {
    if (line.startsWith('```')) fence = !fence
    const h = !fence && /^#{3,6} (.+)$/.exec(line)
    if (h) anchors.set(githubSlug(h[1]), `/api/${slug}#${vitepressSlug(h[1].replace(/`/g, ''))}`)
  }
}

const rewriteLinks = (text) => text.replace(/\]\(#([^)]+)\)/g, (match, anchor) => {
  const target = anchors.get(anchor)
  return target ? `](${target})` : match
})

const escapeHtmlOutsideCode = (text) => {
  let fence = false
  return text.split('\n').map((line) => {
    if (line.startsWith('```')) { fence = !fence; return line }
    if (fence) return line
    return line.split(/(`[^`]*`)/).map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/\{\{/g, '&#123;&#123;'))).join('')
  }).join('\n')
}

const generatedNote = '<!-- Generated from docs/API.md by docs-site/scripts/build-api-reference.mjs. Edit the source, not this file. -->'
// Generated pages are not in git, so VitePress cannot date them; the sitemap and page date use the source's.
const sourceCommitDate = (() => {
  try {
    return execFileSync('git', ['log', '-1', '--format=%cI', '--', 'docs/API.md'], { cwd: repoRoot, encoding: 'utf8' }).trim()
  } catch {
    return ''
  }
})()
const lastUpdatedLine = sourceCommitDate ? `lastUpdated: ${sourceCommitDate}\n` : ''
const frontmatter = (title) => `---\ntitle: "${title.replace(/"/g, '\\"')}"\neditLink: false\n${lastUpdatedLine}---\n\n${generatedNote}\n\n`

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

for (const page of pages) {
  const heading = page.title === APPENDIX ? 'Every route' : page.title
  const body = escapeHtmlOutsideCode(rewriteLinks(page.body.join('\n').trim()))
  writeFileSync(join(outDir, `${pageSlug(page.title)}.md`), `${frontmatter(heading)}# ${heading}\n\n${body}\n`)
}

const basics = pages.filter((p) => BASICS.has(p.title))
const resources = pages.filter((p) => !BASICS.has(p.title) && p.title !== APPENDIX)
const link = (p) => `/api/${pageSlug(p.title)}`

const index = `${frontmatter('API reference')}# API reference

AlianHub has a REST API for scripts, integrations and AI tools. Every request goes to your own instance (for example \`https://hub.example.com/api/v2/...\`); there is no separate API host.

${escapeHtmlOutsideCode(rewriteLinks(intro.join('\n').trim()))
    .replace('Do not edit this file by hand. ', '')
    .replace('documented in full below', 'documented in full in these pages')}

::: tip Where this comes from
These pages are built from \`docs/API.md\`, which \`npm run api:doc\` generates from the routes the server registers. The machine-readable list of paths, methods, auth and tags is [openapi.json](/openapi.json).
:::

## Start here

${basics.map((p) => `- [${p.title}](${link(p)})`).join('\n')}

## Endpoints by area

${resources.map((p) => `- [${p.title}](${link(p)})`).join('\n')}

## Everything else

- [Every route](/api/all-routes) — every other route the server registers, with its auth and status.
- [MCP server](/ai/mcp-server) — the tools an AI app can call.
`
writeFileSync(join(outDir, 'index.md'), index)

const sidebar = [
  { text: 'API reference', items: [{ text: 'Overview', link: '/api/' }] },
  { text: 'Basics', items: basics.map((p) => ({ text: p.title, link: link(p) })) },
  { text: 'Endpoints', items: resources.map((p) => ({ text: p.title, link: link(p) })) },
  { text: 'Reference', items: [{ text: 'Every route', link: '/api/all-routes' }, { text: 'MCP server', link: '/ai/mcp-server' }] },
]
writeFileSync(join(site, '.vitepress/api-sidebar.mjs'), `// Generated by scripts/build-api-reference.mjs.\nexport const apiSidebar = ${JSON.stringify(sidebar, null, 2)}\n`)

mkdirSync(join(site, 'public'), { recursive: true })
copyFileSync(join(repoRoot, 'docs/api/openapi.json'), join(site, 'public/openapi.json'))

console.log(`API reference: ${pages.length} pages from docs/API.md`)
